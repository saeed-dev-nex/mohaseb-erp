def level_for_code(code, parent_code):
    """Tree level: ۱ گروه، ۲ کل، ۳ معین (deeper codes → تفصیلی ۴)."""
    if parent_code is None:
        return 1
    if len(code) <= 2:
        return 2
    if len(code) <= 4:
        return 3
    return 4
